def benign_catalogue() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for name, version, category, notes in [
        *BENIGN_HARD_NEGATIVES,
        *BENIGN_HARD_NEGATIVES_V2,
    ]:
        key = (name, version)
        if key in seen:
            continue
        seen.add(key)
        rows.append(
            {
                "package_name": name,
                "version": version,
                "hard_negative_category": category,
                "notes": notes,
            }
        )
    return rows
